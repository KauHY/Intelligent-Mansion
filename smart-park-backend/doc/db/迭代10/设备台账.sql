CREATE TABLE `com_multistage_category` (
  `id` varchar(32) NOT NULL,
  `parent_id` varchar(32) DEFAULT NULL COMMENT '父id',
  `park_org_id` varchar(64) DEFAULT NULL COMMENT '园区id',
  `type` varchar(50) DEFAULT NULL COMMENT '类型',
  `hierarchy` int unsigned DEFAULT '0' COMMENT '层级，顶级为0',
  `expand` tinyint(1) DEFAULT '1' COMMENT '是否能扩展：0-否；1-是',
  `selectable` tinyint(1) DEFAULT '1' COMMENT '是否可选：0-否；1-是',
  `disabled` tinyint(1) unsigned zerofill DEFAULT '0' COMMENT '禁用：0-否；1-是',
  `label` varchar(500) DEFAULT NULL COMMENT '名称',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `create_by` varchar(64) DEFAULT NULL COMMENT '创建人',
  `update_by` varchar(64) DEFAULT NULL COMMENT '更新人',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除：0否1是',
  PRIMARY KEY (`id`),
  KEY `cmc_idx_parent_id` (`parent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='多级分类表';

